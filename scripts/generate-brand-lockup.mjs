/*
 * Transcribe the approved logo files into renderable data.
 *
 *   node scripts/generate-brand-lockup.mjs
 *
 * The site draws every graphic as inline SVG and loads no image files — a rule
 * its tests enforce across the home page, the services cards, the case study
 * and the demo. The approved logos therefore cannot be referenced with <img>,
 * and they must not be rebuilt out of the site's own fonts either: the supplied
 * lettering is outlined, with its own widths and spacing.
 *
 * So the shapes are lifted out of the approved files verbatim and written to a
 * module the component renders. The path data is the artwork's own; nothing is
 * redrawn, refitted or re-spaced. Re-run this after any change to the files in
 * public/brand and the lockup follows them.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const SOURCES = {
  lockup: 'public/brand/ajani-healthcare-logo-colour-transparent.svg',
  /* The guide's dark-ground artwork: teal plate, ivory letter, gold dot and
     ivory lettering. Its own navy ground rect is dropped below, because the
     surface it sits on supplies one. */
  lockupDark: 'public/brand/ajani-healthcare-logo-colour-navy.svg',
  lockupInverse: 'public/brand/ajani-healthcare-logo-white-transparent.svg',
  symbol: 'public/brand/ajani-symbol-colour-transparent.svg',
};

const attribute = (tag, name) => tag.match(new RegExp(`${name}="([^"]*)"`))?.[1] ?? null;

/**
 * Every drawable element of an approved file, in document order.
 *
 * The pack nests the symbol inside a `<g transform>`, so a group's transform is
 * composed onto its children rather than dropped — losing it would leave the
 * "A" at a sixty-fourth of its size in the corner of the plate.
 */
function shapes(svg) {
  /* Only the drawing elements. The metadata block carries no geometry. */
  const body = svg.slice(svg.indexOf('</metadata>') + '</metadata>'.length);
  const found = [];

  /* Group transforms, pushed and popped as the tags are walked. */
  const open = [];
  const tags = body.match(/<(g|\/g|rect|path|circle)\b[^>]*>/g) ?? [];

  const combine = (own) => {
    const all = [...open, own].filter(Boolean);
    return all.length === 0 ? null : all.join(' ');
  };

  for (const tag of tags) {
    if (tag.startsWith('</g')) { open.pop(); continue; }
    if (tag.startsWith('<g')) { open.push(attribute(tag, 'transform')); continue; }

    const transform = combine(attribute(tag, 'transform'));
    const fill = attribute(tag, 'fill');
    /*
     * Stroke matters as much as fill here. The single-ink artwork draws its
     * plate as `fill="none" stroke="#FFFFFF"`, so reading only the fill threw
     * the plate away and left a letter floating with no badge around it.
     */
    const stroke = attribute(tag, 'stroke');
    const strokeWidth = attribute(tag, 'stroke-width');
    const ink = {
      fill,
      ...(stroke ? { stroke } : {}),
      ...(strokeWidth ? { strokeWidth: Number(strokeWidth) } : {}),
      ...(transform ? { transform } : {}),
    };

    if (tag.startsWith('<rect')) {
      found.push({
        tag: 'rect',
        x: Number(attribute(tag, 'x') ?? 0),
        y: Number(attribute(tag, 'y') ?? 0),
        width: Number(attribute(tag, 'width')),
        height: Number(attribute(tag, 'height')),
        rx: Number(attribute(tag, 'rx') ?? 0),
        ...ink,
      });
    } else if (tag.startsWith('<circle')) {
      found.push({
        tag: 'circle',
        cx: Number(attribute(tag, 'cx')),
        cy: Number(attribute(tag, 'cy')),
        r: Number(attribute(tag, 'r')),
        ...ink,
      });
    } else {
      found.push({ tag: 'path', d: attribute(tag, 'd'), ...ink });
    }
  }

  /*
   * A rect covering the whole canvas is the artwork's own background, which an
   * inline lockup must not carry: the page supplies the surface, and a baked-in
   * ground would show as a coloured block the moment that surface changed.
   */
  const box = viewBox(svg);
  return found.filter((shape) => !(
    shape.tag === 'rect' && shape.width === box.width && shape.height === box.height
  ));
}

function viewBox(svg) {
  const box = attribute(svg, 'viewBox').split(/\s+/).map(Number);
  return { viewBox: attribute(svg, 'viewBox'), width: box[2], height: box[3] };
}

const artwork = {};
for (const [key, path] of Object.entries(SOURCES)) {
  const svg = readFileSync(join(ROOT, path), 'utf8');
  artwork[key] = { source: path, ...viewBox(svg), shapes: shapes(svg) };
  console.log(`  ${path.padEnd(52)} ${artwork[key].shapes.length} shapes`);
}

const module = `/*
 * The approved logo artwork, as data.
 *
 * Generated by scripts/generate-brand-lockup.mjs from the files named in
 * \`source\` below. Every coordinate is the artwork's own — the lettering is
 * outlined in the supplied files and is reproduced here unchanged, never set
 * in one of the site's typefaces.
 *
 * Do not edit by hand. Change the file in public/brand and re-run the script.
 *
 * Ajani Healthcare — logo v1. Creator: Olasupo Ajani.
 * © 2026 Ajani Healthcare Limited. https://www.ajanihealthcare.com
 */

export const BRAND_ARTWORK = ${JSON.stringify(artwork, null, 2)};
`;

writeFileSync(join(ROOT, 'src/lib/brandLockupArtwork.js'), module);
console.log('  src/lib/brandLockupArtwork.js written');
